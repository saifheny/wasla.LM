const abs = p => new URL(p, SITE_URL).href;

export function jsonLd() {
  const shareImg = abs(SHARE_IMAGE_PATH);
  const org = {
    '@type': 'Organization',
    '@id': abs('#org'),
    name: 'وصلة',
    alternateName: ['Wasla', 'وصلة للخدمات'],
    url: SITE_URL,
    logo: { '@type': 'ImageObject', url: abs('assets/icon-512.png'), width: 512, height: 512 },
    image: shareImg,
    description: DESCRIPTION,
    areaServed: { '@type': 'Country', name: 'مصر', identifier: 'EG' }
  };
  const site = {
    '@type': 'WebSite',
    '@id': abs('#site'),
    name: 'وصلة',
    alternateName: 'Wasla',
    url: SITE_URL,
    inLanguage: 'ar-EG',
    publisher: { '@id': abs('#org') }
  };
  const app = {
    '@type': 'WebApplication',
    name: 'وصلة',
    url: SITE_URL,
    applicationCategory: 'LifestyleApplication',
    operatingSystem: 'Any',
    browserRequirements: 'Requires JavaScript',
    inLanguage: 'ar-EG',
    image: shareImg,
    publisher: { '@id': abs('#org') }
  };
  const service = {
    '@type': 'Service',
    name: 'طلب وتقديم كافة الخدمات والصنايعية في مصر',
    serviceType: 'منصة ربط العملاء بمقدمي الخدمات في جميع المجالات',
    provider: { '@id': abs('#org') },
    areaServed: GOVERNORATES.map(g => ({ '@type': 'AdministrativeArea', name: g })),
    hasOfferCatalog: {
      '@type': 'OfferCatalog',
      name: 'خدمات وصلة',
      itemListElement: SERVICES.map(([cat, subs]) => ({
        '@type': 'OfferCatalog',
        name: cat,
        itemListElement: subs.map(s => ({ '@type': 'Offer', itemOffered: { '@type': 'Service', name: s } }))
      }))
    }
  };
  const faq = {
    '@type': 'FAQPage',
    mainEntity: FAQ.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } }))
  };
  return JSON.stringify({ '@context': 'https://schema.org', '@graph': [org, site, app, service, faq] }).replace(/</g, '\\u003c');
}

const escAttr = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

