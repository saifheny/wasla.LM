/* البحث الذكي بالعربي والمرادفات المصرية */
const AN = t => String(t || '').toLowerCase()
  .replace(/[\u064B-\u0652\u0640]/g, '')
  .replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
  .replace(/[^\u0600-\u06FFa-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
const stem = w => w.replace(/^(وال|بال|كال|ال|لل)/, '');
const lev1 = (a, b) => {
  if (Math.abs(a.length - b.length) > 1) return false;
  let i = 0, j = 0, e = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) { i++; j++; continue; }
    if (++e > 1) return false;
    if (a.length > b.length) i++; else if (a.length < b.length) j++; else { i++; j++; }
  }
  return e + (a.length - i) + (b.length - j) <= 1;
};
const CKW = CATS.map((c, i) => [...new Set(AN(c[0] + ' ' + KW[i][1] + ' ' + (SUBS[i] || []).join(' ')).split(' ').map(stem))].filter(w => w.length > 1));
const wm = (w, t) => w === t ? 3 : (t.length > 1 && w.startsWith(t)) ? 2 : (t.length > 2 && w.includes(t)) ? 1.5 : (t.length > 3 && w.length > 3 && lev1(w, t)) ? 1.2 : 0;

function smart(q) {
  const toks = AN(q).split(' ').map(stem).filter(Boolean);
  if (!toks.length) return { cats: [], provs: [], reqs: [] };
  const cs = CKW.map(ws => toks.reduce((a, t) => a + Math.max(0, ...ws.map(w => wm(w, t))) / 3, 0));
  const score = (blob, c) => {
    const ws = AN(blob).split(' ').map(stem);
    let s = 0;
    toks.forEach(t => { s += Math.max(0, ...ws.map(w => wm(w, t))); });
    return s + (c >= 0 ? cs[c] * 2.5 : 0);
  };
  const top = (arr, fn) => arr.map(x => ({ x, s: fn(x) })).filter(o => o.s >= 1.2).sort((a, b) => b.s - a.s).map(o => o.x);
  return {
    cats: CATS.map((c, i) => i).filter(i => cs[i] >= 0.6 || score(CATS[i][0], -1) >= 2).slice(0, 3),
    provs: top(PROV.map((p, i) => ({ p, i })), o => score(o.p.n + ' ' + (o.p.spec || '') + ' ' + CATS[o.p.c][0] + ' ' + o.p.loc + ' ' + (o.p.bio || ''), o.p.c)).slice(0, 10),
    reqs: top(REQS.filter(r => r.rawStatus !== 'cancelled'), r => score(r.t + ' ' + r.d + ' ' + (r.sub || '') + ' ' + CATS[r.c][0] + ' ' + r.loc, r.c)).slice(0, 10)
  };
}

